-- 修：沒登入的人讀不到 /apply/ 與 /resources/。　2026-09-08
--
-- 用法：整份貼進 Supabase SQL Editor 按一次 Run。前面六支都要先跑過。
--
-- ============================================================================
-- 症狀
-- ============================================================================
-- 打開 /apply/ 或 /resources/（沒登入）會看到「現在連不上資料庫」。
-- 資料庫回的是：
--     ERROR:  permission denied for function is_on_team
--     ERROR:  permission denied for function is_director_of
--
-- ============================================================================
-- 原因
-- ============================================================================
-- 那兩張表的 RLS 政策長這樣：
--     forms_read      using (status = 'open'      or public.is_on_team(team))
--     res_read        using (status = 'published' or public.is_director_of(team))
--
-- 而那幾支函式當初照 is_cadre() 的樣子寫，**把 anon 的執行權限收掉了**：
--     revoke execute ... from public, anon;
--     grant  execute ... to authenticated;
--
-- 於是沒登入的人一讀那張表，Postgres 要評估政策、要呼叫那支函式，
-- 而他沒有執行權限 —— **整個查詢失敗，不是「讀到零列」**。
--
-- ⚠ 不要靠 `or` 的短路來繞過（例如寫成 `auth.uid() is not null and is_on_team(...)`）。
-- 規劃器可以自由決定 OR / AND 兩邊的評估順序，短路不是保證。
--
-- ============================================================================
-- 為什麼發給 anon 是安全的
-- ============================================================================
-- 這四支回的都是「**呼叫者自己**是不是某種身分」的布林值，
-- 不回傳任何一列資料。對沒登入的人來說 auth.uid() 是 null，四支一律回 false。
-- 換句話說：發給 anon 之後，他能問到的只有「我不是」。
--
-- 當初收掉 anon 是對的 —— 那時候沒有任何一條政策需要 anon 評估它們。
-- 現在 /apply/、/resources/、/team/ 三頁都要在沒登入的情況下讀資料，前提變了。
--
-- ============================================================================
-- 這個 bug 為什麼沒有被本機的 smoke.sh 抓到
-- ============================================================================
-- 那支腳本用超級使用者跑，而**超級使用者繞過 RLS**，政策一次都沒有被評估。
-- 腳本的檔頭老實寫了「RLS 驗不到」，然後這個洞就從那裡掉出去了。
-- 已經補上：smoke.sh 現在會用 anon 與 authenticated 的身分各讀一次。

begin;

-- is_cadre 也要：/team/ 的 profiles_read 政策裡有它，而那一頁沒登入也要讀得到
-- 已經公開的那幾列。
grant execute on function public.is_cadre()             to anon;
grant execute on function public.is_on_team(text)       to anon;
grant execute on function public.is_director_of(text)   to anon;
-- is_president 目前沒有出現在任何 anon 讀得到的政策裡，但它跟上面三支同一類，
-- 而且**下一條政策很可能會用到它**。四支一起發，行為才一致 ——
-- 不然下一個人加政策時會再撞一次同一面牆，而錯誤訊息看起來像權限設錯了。
grant execute on function public.is_president()         to anon;

commit;

-- ============================================================================
-- 跑完之後怎麼確認
-- ============================================================================
